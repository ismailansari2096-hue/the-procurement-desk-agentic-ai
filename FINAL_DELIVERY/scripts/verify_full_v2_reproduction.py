"""
Full 2,000-thread V2 Reproduction Verification Script.
Runs the complete Agentic Orchestrator (mode='v2') across all 2,000 official threads in data/raw/threads.csv.
Compares predictions against outputs/experimental/submission_v2.csv row-by-row.
"""

import sys
import csv
import hashlib
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR / "src"))

from agentic.orchestrator import NegotiationOrchestrator
from procurement.data_loader import load_threads

THREADS_PATH = BASE_DIR / "data" / "raw" / "threads.csv"
V2_SUBMISSION_PATH = BASE_DIR / "outputs" / "experimental" / "submission_v2.csv"


def compute_sha256(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def main():
    print("=" * 70)
    print("STEP 1: FULL V2 2,000-THREAD REPRODUCTION AUDIT")
    print("=" * 70)

    # 1. Load official threads
    threads = load_threads(THREADS_PATH)
    print(f"[+] Loaded official test threads: {len(threads)} rows")

    # 2. Load existing V2 submission
    with open(V2_SUBMISSION_PATH, "r", encoding="utf-8") as f:
        v2_rows = list(csv.DictReader(f))
    print(f"[+] Loaded existing V2 submission: {len(v2_rows)} rows")

    # 3. Check existing V2 submission SHA-256
    with open(V2_SUBMISSION_PATH, "rb") as f:
        existing_v2_sha256 = compute_sha256(f.read())
    print(f"[+] Existing submission_v2.csv SHA-256: {existing_v2_sha256}")

    # 4. Run the complete agentic pipeline across all 2,000 threads
    print("\n[+] Executing Agentic NegotiationOrchestrator(mode='v2') on all 2,000 threads...")
    orchestrator = NegotiationOrchestrator(mode="v2")

    generated_predictions = []
    generated_rows = []

    for idx, thread in enumerate(threads):
        label = orchestrator.decide(thread)
        tid = thread["thread_id"]
        generated_predictions.append((tid, label))
        generated_rows.append({"thread_id": tid, "label": label})

    print(f"[+] Agentic engine generation complete: {len(generated_predictions)} predictions.")

    # 5. Row-by-row comparison
    total_threads = len(threads)
    total_existing = len(v2_rows)
    total_generated = len(generated_rows)

    seen_gen_ids = set()
    duplicate_gen_ids = []
    for r in generated_rows:
        tid = r["thread_id"]
        if tid in seen_gen_ids:
            duplicate_gen_ids.append(tid)
        seen_gen_ids.add(tid)

    seen_v2_ids = set(r["thread_id"] for r in v2_rows)
    missing_in_gen = [tid for tid in seen_v2_ids if tid not in seen_gen_ids]
    missing_in_v2 = [tid for tid in seen_gen_ids if tid not in seen_v2_ids]

    matching_rows = 0
    different_rows = []

    for idx in range(total_threads):
        v2_r = v2_rows[idx]
        gen_r = generated_rows[idx]

        v2_id, v2_label = v2_r["thread_id"], v2_r["label"]
        gen_id, gen_label = gen_r["thread_id"], gen_r["label"]

        if v2_id != gen_id:
            different_rows.append((idx, v2_id, gen_id, v2_label, gen_label, "ID_MISMATCH"))
        elif v2_label != gen_label:
            different_rows.append((idx, v2_id, gen_id, v2_label, gen_label, "LABEL_MISMATCH"))
        else:
            matching_rows += 1

    # In-memory CSV serialization to compute SHA-256 of generated output
    # formatted identically (CRLF on Windows / standard csv writer)
    from io import StringIO
    sio = StringIO()
    writer = csv.DictWriter(sio, fieldnames=["thread_id", "label"], lineterminator="\r\n")
    writer.writeheader()
    writer.writerows(generated_rows)
    generated_csv_bytes = sio.getvalue().encode("utf-8")
    generated_v2_sha256 = compute_sha256(generated_csv_bytes)

    print("\n" + "=" * 70)
    print("AUDIT FINDINGS:")
    print("=" * 70)
    print(f"Total official threads in threads.csv:  {total_threads}")
    print(f"Total rows in existing submission_v2:   {total_existing}")
    print(f"Total rows generated by agentic engine: {total_generated}")
    print(f"Duplicate IDs in generated output:      {len(duplicate_gen_ids)}")
    print(f"Missing IDs vs existing V2:             {len(missing_in_gen)}")
    print(f"Extra IDs vs existing V2:               {len(missing_in_v2)}")
    print(f"Exact matching rows:                    {matching_rows} / {total_threads} ({matching_rows/total_threads*100:.2f}%)")
    print(f"Different labels:                       {len(different_rows)}")
    print(f"Existing submission_v2.csv SHA-256:     {existing_v2_sha256}")
    print(f"Generated output SHA-256:               {generated_v2_sha256}")
    print(f"Exact SHA-256 byte match:               {existing_v2_sha256 == generated_v2_sha256}")

    if different_rows:
        print("\nFirst 10 differing rows:")
        for diff in different_rows[:10]:
            print(f"  Row {diff[0]}: ID {diff[1]} -> Existing: '{diff[3]}' vs Generated: '{diff[4]}' ({diff[5]})")
        sys.exit(1)
    else:
        print("\n[SUCCESS] The agentic architecture reproduces submission_v2.csv with 100.0% EXACTNESS.")
        sys.exit(0)


if __name__ == "__main__":
    main()
